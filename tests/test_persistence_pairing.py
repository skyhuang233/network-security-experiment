ADAPTERS = {
    "M1": M1FileContentChannel,
    "M2": M2DirNameChannel,
    "M3": M3CacheStateChannel,
}


def _publish_and_receive(method: str, td: str, payload: bytes,
                         key_set_size: int = 128):
    config = CaseRunConfig(
        case_run_id="t", case_id="x", seed=0, method=method,
        key_set_size=key_set_size,
    )
    mlog = MeasurementLog(method, "t")
    adapter = ADAPTERS[method](root=td, measurement=mlog, config=config)
    views = build_views(adapter, config)
    adapter.set_round(1)
    adapter.send_payload(0, payload, view=views[0])
    if method == "M3":
        round_ = 1
        while any(adapter._inflight[0]) and round_ < 500:
            adapter.set_round(round_)
            adapter.publish_round_end()
            round_ += 1
    else:
        adapter.publish_round_end()
    return adapter, views


def _fresh_receive(method: str, td: str, payload: bytes,
                   key_set_size: int = 128):
    config = CaseRunConfig(
        case_run_id="t-rx", case_id="x", seed=0, method=method,
        key_set_size=key_set_size,
    )
    rx_log = MeasurementLog(method, "t-rx")
    rx_adapter = ADAPTERS[method](root=td, measurement=rx_log, config=config)
    rx_views = build_views(rx_adapter, config)
    rx_adapter.set_round(2)
    msgs = rx_adapter.receive(1, view=rx_views[1])
    return any(m.sender == 0 and m.data == payload for m in msgs)


class PayloadProvenanceTest(unittest.TestCase):
    def test_payload_info_stable(self) -> None:
        b = bytes(range(9))
        i1, i2 = payload_info(b), payload_info(b)
        self.assertEqual(i1, i2)
        self.assertEqual(i1["bytes"], 9)
        self.assertEqual(len(i1["sha256"]), 64)
        self.assertEqual(i1["hex"], b.hex())


class CommonActiveCleanupTest(unittest.TestCase):
    """Active cleanup is a per-carrier control, not an M3-only expire()."""

    def _roundtrip(self, method: str, payload: bytes) -> None:
        with tempfile.TemporaryDirectory() as td:
            adapter, _ = _publish_and_receive(method, td, payload)
            # without cleanup the fresh receiver recovers the payload
            self.assertTrue(_fresh_receive(method, td, payload))
            # common active cleanup physically removes the live objects
            info = run_active_cleanup(adapter, method)
            self.assertGreaterEqual(info["objects_removed"], 1)
            self.assertFalse(_fresh_receive(method, td, payload))

    def test_m1_cleanup_removes_files(self) -> None:
        self._roundtrip("M1", b"m1-paired-payload")

    def test_m2_cleanup_removes_dirs(self) -> None:
        self._roundtrip("M2", b"m2-paired-payload")

    def test_m3_cleanup_removes_keys(self) -> None:
        # single-publication-sized payload so one delayed read can recover
        payload = b"x" * m3_single_publication_payload_len(128)
        self._roundtrip("M3", payload)


class M3EvictionPressureTest(unittest.TestCase):
    def test_background_writer_evicts_protocol_keys(self) -> None:
        # the noise writer hammers the SAME cache directory under a small
        # size limit: diskcache LRU eviction removes the (older) protocol
        # keys -- genuine eviction pressure, not a separate noise directory
        payload = b"x" * m3_single_publication_payload_len(128)
        with tempfile.TemporaryDirectory() as td:
            adapter, _ = _publish_and_receive("M3", td, payload)
            cache = adapter._cache(0)
            set_before = [
                k for k in range(adapter.K)
                if adapter._key(0, k) in cache
            ]
            self.assertTrue(set_before)  # protocol keys physically present

            stop = threading.Event()
            t = start_background_writer(
                stop, "M3", Path(td), live_dir=adapter.live_dir,
                cache_size_limit=2**17,  # 128 KiB
                value_bytes=64 * 1024,
                max_writes=16,           # 1 MiB total >> limit: must cull
            )
            t.join(timeout=30)
            stop.set()

            set_after = [
                k for k in range(adapter.K)
                if adapter._key(0, k) in cache
            ]
            self.assertEqual(set_after, [])  # protocol keys evicted
            self.assertFalse(_fresh_receive("M3", td, payload))

    def test_baseline_untouched_by_default_size_limit(self) -> None:
        # without the pressure condition the default 1 GiB limit keeps the
        # publication intact (the condition, not the carrier, changes behavior)
        payload = b"x" * m3_single_publication_payload_len(128)
        with tempfile.TemporaryDirectory() as td:
            _publish_and_receive("M3", td, payload)
            time.sleep(0.2)
            self.assertTrue(_fresh_receive("M3", td, payload))


class SummarizeCurveTest(unittest.TestCase):
    def test_curve_reports_repeat_estimates(self) -> None:
        points = [
            {"delay_seconds": 0, "logically_recovered": True,
             "recovered_count": 3, "repeats": 3, "recovered_fraction": 1.0},
            {"delay_seconds": 10, "logically_recovered": False,
             "recovered_count": 1, "repeats": 3, "recovered_fraction": 1 / 3},
        ]
        s = summarize_curve(points)
        self.assertIn("lost before 10", s["summary"])
        self.assertEqual(s["curve"][1]["recovered_fraction"], 1 / 3)

    def test_all_recovered_summary(self) -> None:
        points = [
            {"delay_seconds": 60, "logically_recovered": True,
             "recovered_count": 3, "repeats": 3, "recovered_fraction": 1.0},
        ]
        s = summarize_curve(points)
        self.assertIn("recoverable for at least the tested 60", s["summary"])


